import { chromium } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'

await mkdir('qa', { recursive: true })
const url = process.env.SITE_URL || 'http://127.0.0.1:5173'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const checks = []
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const response = await page.goto(url, { waitUntil: 'networkidle' })
  assert.equal(response.status(), 200)
  await page.locator('main[data-render-mode="webgl"]').waitFor()
  await page.waitForTimeout(2500)
  const canvas = page.locator('.cosmic-scene canvas')
  assert.equal(await page.locator('h1').innerText(), 'ZL AI LAB')
  assert.equal(await page.locator('.hero-tagline').innerText(), 'Building digital tools and intelligent experiences.')
  assert.equal(await page.locator('.core-identity').count(), 0)
  assert.equal(await page.locator('.holo-card').count(), 2)
  assert.equal(await page.locator('.document-card').getAttribute('href'), 'https://github.com/ZLongLab/DocumentAssistant')
  assert.equal(await page.locator('.gateway-card').getAttribute('href'), 'https://github.com/ZLongLab')
  assert.equal(await canvas.getAttribute('data-surface-flow'), 'latitude-spiral-sweep')
  assert.equal(await canvas.getAttribute('data-bloom'), 'mipmap-hdr')
  assert.equal(await page.locator('.document-card .waveform > i').count(), 40)
  assert.equal(await page.locator('.network-flow').count(), 6)
  checks.push('Two real external entrances, flowing particle core, HDR Bloom, ripple spectrum and SVG branch flows')

  const animatedA = await canvas.screenshot()
  const readingsA = await page.locator('[data-reading]').allTextContents()
  const barsA = await page.locator('.document-card .waveform').screenshot()
  await page.waitForTimeout(400)
  assert.ok(!animatedA.equals(await canvas.screenshot()), 'Particle rendering must animate')
  assert.notDeepEqual(await page.locator('[data-reading]').allTextContents(), readingsA, 'Simulated telemetry changes')
  assert.ok(!barsA.equals(await page.locator('.document-card .waveform').screenshot()), 'Spectrum and ripples animate')
  checks.push('Actual WebGL frames, CSS spectrum and simulated telemetry advance')

  const normalDuration = await page.locator('.network-flow').first().evaluate(e => parseFloat(getComputedStyle(e).animationDuration))
  const normalBar = await page.locator('.document-card .waveform > i').first().evaluate(e => parseFloat(getComputedStyle(e).animationDuration))
  await page.locator('.gateway-card').hover()
  const fastDuration = await page.locator('.network-flow').first().evaluate(e => parseFloat(getComputedStyle(e).animationDuration))
  assert.ok(Math.abs(fastDuration/normalDuration - .4) < .01)
  await page.locator('.document-card').hover()
  const fastBar = await page.locator('.document-card .waveform > i').first().evaluate(e => parseFloat(getComputedStyle(e).animationDuration))
  assert.ok(Math.abs(fastBar/normalBar - .4) < .01)
  assert.equal(await page.locator('.document-card').evaluate(e => Number(getComputedStyle(e).getPropertyValue('--tempo'))), .4)
  await page.mouse.move(1200, 400)
  await page.mouse.move(1000, 450, { steps: 12 })
  assert.ok(Number(await canvas.getAttribute('data-trail-particles')) > 0)
  await page.waitForTimeout(450)
  assert.equal(await canvas.getAttribute('data-trail-particles'), '0')
  checks.push('Card hover accelerates data/spectrum animations; tapered pointer feedback expires')

  await page.getByRole('button', { name: '暂停场景动画' }).click()
  await page.mouse.move(650, 150)
  await page.waitForTimeout(250)
  assert.equal(await canvas.getAttribute('data-trail-particles'), '0')
  const frozenA = await page.screenshot()
  const readingsFrozen = await page.locator('[data-reading]').allTextContents()
  await page.waitForTimeout(400)
  assert.ok(frozenA.equals(await page.screenshot()), 'Pause freezes WebGL, SVG, CSS and readings together')
  assert.deepEqual(await page.locator('[data-reading]').allTextContents(), readingsFrozen)
  await page.screenshot({ path: 'qa/command-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '播放场景动画' }).click()
  await page.mouse.move(650, 150)
  const resumedA = await canvas.screenshot()
  await page.waitForTimeout(300)
  assert.ok(!resumedA.equals(await canvas.screenshot()))
  checks.push('Unified toggle freezes and resumes all visual animation and telemetry')

  for (const [width, height] of [[1920,1080],[1440,900],[1024,768],[768,1024],[390,844],[320,640]]) {
    await page.setViewportSize({ width, height })
    await page.waitForTimeout(650)
    const layout = await page.evaluate(() => {
      const box = selector => document.querySelector(selector).getBoundingClientRect().toJSON()
      const canvas = document.querySelector('canvas')
      const canvasBox = canvas.getBoundingClientRect()
      return { width: document.documentElement.scrollWidth, viewport: innerWidth, content: box('.command-column'), stage: box('.orbital-stage'), footer: box('footer'), cards: [...document.querySelectorAll('.holo-card')].map(e=>({ box: e.getBoundingClientRect().toJSON(), scroll:e.scrollWidth, width:e.clientWidth })), coreX:Number(canvas.dataset.coreX)+canvasBox.x, coreY:Number(canvas.dataset.coreY)+canvasBox.y }
    })
    assert.ok(layout.width <= layout.viewport, `Horizontal overflow at ${width}`)
    assert.ok(layout.cards.every(c=>c.scroll <= c.width+1), `Clipped card contents at ${width}`)
    assert.ok(layout.cards[0].box.bottom < layout.cards[1].box.top)
    if (width >= 768) assert.ok(layout.content.right <= layout.stage.left+1, `Desktop columns overlap at ${width}`)
    else assert.ok(layout.content.bottom < layout.stage.top, `Stacked sections overlap at ${width}`)
    assert.ok(layout.footer.top >= Math.max(layout.content.bottom,layout.stage.bottom))
    assert.ok(Math.abs(layout.coreX-layout.stage.x-layout.stage.width/2)<1 && Math.abs(layout.coreY-layout.stage.y-layout.stage.height/2)<1, `Core does not follow right panel at ${width}`)
  }
  checks.push('Desktop columns and mobile stack at 1920/1440/1024/768/390/320px, no clipping; core tracks panel center')

  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(500)
  await page.getByRole('button', { name: '暂停场景动画' }).click()
  await page.screenshot({ path: 'qa/command-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '播放场景动画' }).click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.waitForTimeout(200)
  assert.ok(await page.locator('.motion-control').isDisabled())
  const reducedA = await page.screenshot({ fullPage: true })
  await page.waitForTimeout(300)
  assert.ok(reducedA.equals(await page.screenshot({ fullPage: true })))
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.waitForFunction(() => !document.querySelector('.motion-control').disabled)
  assert.ok(await page.locator('.motion-control').isEnabled())
  checks.push('System reduced-motion preference freezes all effects without hiding content')

  const fallback = await browser.newPage({ reducedMotion: 'reduce' })
  await fallback.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function(type,...args) { if(type.startsWith('webgl')) return null; return original.call(this,type,...args) }
  })
  await fallback.goto(url, { waitUntil: 'networkidle' })
  assert.equal(await fallback.locator('main').getAttribute('data-render-mode'), 'fallback')
  assert.equal(await fallback.locator('.holo-card').count(), 2)
  assert.ok(await fallback.locator('h1').isVisible())
  await fallback.close()
  await canvas.dispatchEvent('webglcontextlost')
  await page.locator('main[data-render-mode="fallback"]').waitFor()
  assert.equal(await page.locator('.holo-card').count(), 2)
  assert.deepEqual(errors, [])
  checks.push('Unavailable/lost WebGL keeps entrances usable; no browser/shader errors')
  const report = { passed: true, checks }
  await writeFile('qa/results-command.json',JSON.stringify(report,null,2))
  console.log(JSON.stringify(report,null,2))
} finally { await browser.close() }
