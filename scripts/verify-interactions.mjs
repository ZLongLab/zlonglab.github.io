import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'

await mkdir('qa',{recursive:true})
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true})
const checks=[]
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}})
 const errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
 const response=await page.goto(process.env.SITE_URL || 'http://127.0.0.1:5173',{waitUntil:'networkidle'})
 assert.equal(response.status(),200)
 await page.locator('main[data-render-mode=webgl]').waitFor()
 await page.waitForTimeout(2400)
 const canvas=page.locator('canvas'), modes=page.getByRole('group',{name:'核心视觉模式'})
 const waitMorph=(key)=>page.waitForFunction(key=>Number(document.querySelector('canvas').dataset[key])>.95,key)
 await modes.getByRole('button',{name:'NETWORK',exact:true}).click()
 await waitMorph('networkMorph')
 await page.screenshot({path:'qa/upgrade-network.png',fullPage:true})
 await modes.getByRole('button',{name:'FLOW',exact:true}).click()
 await waitMorph('flowMorph')
 await page.screenshot({path:'qa/upgrade-flow.png',fullPage:true})
 await modes.getByRole('button',{name:'CORE',exact:true}).click()
 await page.waitForFunction(()=>Number(document.querySelector('canvas').dataset.flowMorph)<.05)
 checks.push('Mode controls produce smooth GPU morphs: CORE, NETWORK, FLOW')
 await page.locator('.document-card').hover()
 await waitMorph('flowMorph')
 assert.equal(await page.locator('main').getAttribute('data-linked'),'document')
 assert.ok((await page.locator('.core-caption').textContent()).includes('DOCUMENT ASSISTANT'))
 assert.equal(await page.locator('.bridge-active').count(),1)
 await page.screenshot({path:'qa/upgrade-linked.png',fullPage:true})
 await page.locator('.gateway-card').hover()
 await waitMorph('networkMorph')
 assert.equal(await page.locator('main').getAttribute('data-linked'),'github')
 await page.mouse.move(650,140)
 await page.waitForFunction(()=>Number(document.querySelector('canvas').dataset.networkMorph)<.05)
 await page.locator('.document-card').focus()
 assert.equal(await page.locator('main').getAttribute('data-linked'),'document')
 await modes.getByRole('button',{name:'CORE',exact:true}).focus()
 assert.equal(await page.locator('main').getAttribute('data-linked'),'idle')
 checks.push('Both card uplinks drive particle modes, data ribbon and captions; keyboard focus works and leaving restores selected mode')
 const zone=page.getByRole('button',{name:'点击核心释放能量波，鼠标拖动旋转'})
 await zone.click()
 await page.waitForTimeout(150)
 assert.ok(Number(await canvas.getAttribute('data-pulse-age'))<1.5)
 await page.waitForFunction(()=>Number(document.querySelector('canvas').dataset.attraction)>.5)
 const box=await zone.boundingBox()
 await page.mouse.move(box.x+box.width*.5,box.y+box.height*.5)
 await page.mouse.down()
 await page.mouse.move(box.x+box.width*.8,box.y+box.height*.6,{steps:15})
 await page.mouse.up()
 await page.waitForFunction(()=>Number(document.querySelector('canvas').dataset.dragRotation)>.15)
 assert.ok(!(await zone.getAttribute('class')).includes('is-dragging'))
 await page.waitForTimeout(1600)
 await zone.focus()
 await page.keyboard.press('Enter')
 await page.waitForTimeout(100)
 assert.ok(Number(await canvas.getAttribute('data-pulse-age'))<.8)
 checks.push('Core click/Enter triggers energy wave; proximity attracts particles; captured mouse drag rotates assembly')
 await page.mouse.move(650,140)
 await page.waitForTimeout(700)
 await page.getByRole('button',{name:'暂停场景动画'}).click()
 await page.waitForTimeout(300)
 const still=await page.screenshot()
 await page.waitForTimeout(400)
 assert.ok(still.equals(await page.screenshot()),'New HUD, projection deck, morphs, nucleus and telemetry must all pause')
 assert.ok(await zone.isDisabled())
 assert.ok(await modes.getByRole('button',{name:'FLOW',exact:true}).isDisabled())
 await page.screenshot({path:'qa/upgrade-desktop.png',fullPage:true})
 await page.getByRole('button',{name:'播放场景动画'}).click()
 checks.push('Unified pause freezes every added subsystem and prevents hidden input changes')
 await page.setViewportSize({width:390,height:844})
 await page.waitForTimeout(650)
 await modes.getByRole('button',{name:'NETWORK',exact:true}).click()
 await waitMorph('networkMorph')
 await page.screenshot({path:'qa/upgrade-mobile.png',fullPage:true})
 const bounds=await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth,stage:document.querySelector('.orbital-stage').getBoundingClientRect().toJSON(),controls:document.querySelector('.scene-modes').getBoundingClientRect().toJSON(),footer:document.querySelector('footer').getBoundingClientRect().toJSON()}))
 assert.ok(bounds.width<=bounds.viewport)
 assert.ok(bounds.controls.left>=0 && bounds.controls.right<=bounds.viewport && bounds.controls.bottom<=bounds.footer.top)
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.waitForTimeout(300)
 const reduced=await page.screenshot({fullPage:true})
 await page.waitForTimeout(300)
 assert.ok(reduced.equals(await page.screenshot({fullPage:true})))
 checks.push('Mobile controls fit, touch page keeps native scrolling, reduced motion freezes all new effects')
 assert.deepEqual(errors,[])
 const report={passed:true,checks,errors}
 await writeFile('qa/results-upgrade.json',JSON.stringify(report,null,2))
 console.log(JSON.stringify(report,null,2))
} finally {await browser.close()}
